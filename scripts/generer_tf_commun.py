"""Builds app/tfCommun.tsx from app/Vigil.tsx: the map toolkit shared by the Trends & Forecasts view.

    python scripts/generer_tf_commun.py

Vigil.tsx (the Analytics view) is NOT modified: its building blocks are private to the file, so this script copies
them verbatim (country list, formatting, Gall-Peters projection, region-card fields, drag hook, stylesheet) into
a module that exports them. Run it again after a change of Vigil.tsx to keep both views visually identical.
"""
import os
import re

RACINE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(RACINE, "app", "Vigil.tsx"), encoding="utf-8").read()


def bloc(debut, fin, inclure_fin=False):
    a = src.index(debut)
    b = src.index(fin, a + len(debut))
    return src[a:b + (len(fin) if inclure_fin else 0)].rstrip() + "\n"


SEP = "/* ────────────────────────────────────────────────────────────────────────── */"
parties = [
    bloc("const MONTHS = [", "\n", True),
    bloc("const COUNTRIES: Array<", "type Lieu ="),
    bloc("type Lieu =", SEP),
    bloc("const clamp = ", "const unit = "),
    bloc("const rectRing = ", SEP),
    bloc("const MORPH_MS = ", "\n", True),
    bloc("const TAILLE_RES:", "/** Check if [lon, lat]"),
    bloc("/** Check if [lon, lat]", "function hexFeatures("),
    bloc("const ESRI = ", "let gpProtocole = false;"),
    bloc("function niceTicks(", SEP),
    bloc("const bboxToSizeKm = ", "interface RegionCardProps"),
    bloc("/** Region name with its Rename button", "function RegionCard("),
    bloc("const EMPTY_FC = ", "\n", True),
    bloc("function ExpandIcon()", "export default function Vigil()"),
    bloc("const CSS = PALETTE_CSS + `", "`;", True),
]
dd = open(os.path.join(RACINE, "app", "DeepDive.tsx"), encoding="utf-8").read()
a = dd.index("type Pop = ")
parties.append(dd[a:dd.index("/* ── Props")].rstrip() + "\n")      # definition tooltip (Def)
a = dd.index("const DD_CSS = `")
parties.append(dd[a:dd.index("`;", a) + 2] + "\n")                  # dashboard stylesheet
corps = "\n".join(parties)
# export every top-level declaration
corps = re.sub(r"^(const|let|function|async function|type|interface) ", r"export \1 ", corps, flags=re.M)

tete = '''"use client";

/**
 * GENERATED by scripts/generer_tf_commun.py from app/Vigil.tsx - do not edit by hand.
 * Map toolkit of the Trends & Forecasts view, copied verbatim from the Analytics view so that both look and behave
 * the same (countries, number formats, Gall-Peters projection, region-card fields, draggable panels, stylesheet).
 */
import React, { useEffect, useId, useRef, useState } from "react";
import { createPortal } from "react-dom";
import type { StyleSpecification } from "maplibre-gl";
import { cellArea } from "h3-js";
import type { Ring } from "./donnees";
import { PALETTE_CSS } from "./palette";

export interface RegionDef {
  id: string;
  name: string;
  /** [latMin, latMax, lonMin, lonMax] */
  bbox: [number, number, number, number];
  /** Country key (Trends & Forecasts: Natural Earth name of the cells table). */
  pays?: string;
}

/** Registers the "gp://" protocol (Gall-Peters tiles) once per page. */
let gpPret = false;
export function enregistrerGallPeters(maplibregl: { addProtocol: (nom: string, f: (p: { url: string }, ac: AbortController) => Promise<{ data: ImageBitmap }>) => void }) {
  if (gpPret) return;
  gpPret = true;
  maplibregl.addProtocol("gp", (p, ac) => tuileGallPeters(p.url, ac.signal).then((data) => ({ data })));
}

'''
out = os.path.join(RACINE, "app", "tfCommun.tsx")
open(out, "w", encoding="utf-8", newline="\n").write(tete + corps)
print(out, len((tete + corps).splitlines()), "lignes")
